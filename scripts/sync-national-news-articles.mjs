/**
 * يقرأ content/national-news/articles/*.json ويولّد ملف TypeScript
 * مضمّن في الحزمة — ضروري لأن Cloudflare Worker لا يقرأ نظام الملفات وقت التشغيل.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const articlesDir = path.join(root, "content", "national-news", "articles");
const outDir = path.join(root, "lib", "generated");
const outFile = path.join(outDir, "national-news-articles.ts");

const TEAM = {
  ahmedFathy: "ahmed-fathy",
  mohammedAhmad: "mohammed-ahmad",
  saraHarbi: "sara-harbi",
  fahedShamri: "fahed-shamri",
  abdullahQhtani: "abdullah-qhtani",
};

const pestPattern = /حشر|pest|صراص|بق|نمل|رش|آفات|مبيد/i;
const tanksFacadesPattern = /خزان|واجه|tank|facade|pool|مياه|مكيف|مسابح|swa/i;

function inferNewsAuthorId(slug, data) {
  if (data.authorId) return String(data.authorId);
  const haystack = [slug, data.title, data.excerpt, ...(Array.isArray(data.keywords) ? data.keywords : [])]
    .filter(Boolean)
    .join(" ");
  if (pestPattern.test(haystack)) return TEAM.fahedShamri;
  if (tanksFacadesPattern.test(haystack)) return TEAM.abdullahQhtani;
  if (/نظافة|تنظيف|صحة|hygiene|clean|food|غذاء/i.test(haystack)) return TEAM.mohammedAhmad;
  if (/سياحة|ضيافة|مدرسة|tourism|school|hospitality/i.test(haystack)) return TEAM.saraHarbi;
  return TEAM.ahmedFathy;
}

function parseArticle(fileName) {
  const slug = fileName.replace(/\.json$/i, "");
  if (!slug || slug.startsWith("_")) return null;

  const raw = fs.readFileSync(path.join(articlesDir, fileName), "utf8");
  const data = JSON.parse(raw);
  if (!data.title || typeof data.excerpt !== "string" || typeof data.bodyMd !== "string") return null;
  if (!data.sourceUrl || !data.publishedAt) return null;

  return {
    ...data,
    slug,
    sourceUrl: String(data.sourceUrl).trim(),
    authorId: inferNewsAuthorId(slug, data),
  };
}

function main() {
  if (!fs.existsSync(articlesDir)) {
    console.warn("[sync-national-news] مجلد articles غير موجود — ملف فارغ.");
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(
      outFile,
      `/** Generated — no articles dir */\nimport type { NationalNewsArticle } from "@/lib/national-news-types";\nexport const staticNationalNewsArticles: NationalNewsArticle[] = [];\nexport function getStaticNationalNewsSlugs(): string[] { return []; }\n`,
      "utf8",
    );
    return;
  }

  const articles = fs
    .readdirSync(articlesDir)
    .filter((n) => n.endsWith(".json") && !n.startsWith("_"))
    .map(parseArticle)
    .filter(Boolean)
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime());

  fs.mkdirSync(outDir, { recursive: true });

  const body = `/** Auto-generated by scripts/sync-national-news-articles.mjs — لا تعدّل يدوياً */
import type { NationalNewsArticle } from "@/lib/national-news-types";

export const staticNationalNewsArticles: NationalNewsArticle[] = ${JSON.stringify(articles, null, 2)} as NationalNewsArticle[];

export function getStaticNationalNewsSlugs(): string[] {
  return staticNationalNewsArticles.map((a) => a.slug);
}
`;

  fs.writeFileSync(outFile, body, "utf8");
  console.log(`[sync-national-news] ${articles.length} خبر → lib/generated/national-news-articles.ts`);
}

main();
