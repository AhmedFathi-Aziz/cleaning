export function buildUniqueFaqs(ctx: UniquenessCtx, family: ServiceFamily, serviceLabel: string): ServiceLocationFaq[] {
  const specific = getNeighborhoodSpecificContent(ctx.citySlug, ctx.neighborhood.slug);
  const hoodFaqEntries = specific?.faqs.filter((f) => f?.question?.trim() && f?.answer?.trim()) ?? [];
  if (hoodFaqEntries.length >= 1) {
    const hoodFaqs: ServiceLocationFaq[] = hoodFaqEntries.slice(0, 4).map((f) => ({
      question: fill(f.question, ctx, serviceLabel),
      answer: fill(f.answer, ctx, serviceLabel),
    }));
    if (hoodFaqs.length < 4) {
      const pools = faqPools[family];
      let i = 0;
      while (hoodFaqs.length < 4 && i < 8) {
        const qIdx = variantIndex(`${ctx.seed}:faq-pad:${i}`, pools.questions.length);
        const q = pools.questions[qIdx];
        const a = pools.answers[qIdx % pools.answers.length];
        if (q && a && !hoodFaqs.some((f) => f.question === fill(q, ctx, serviceLabel))) {
          hoodFaqs.push({ question: fill(q, ctx, serviceLabel), answer: fill(a, ctx, serviceLabel) });
        }
        i++;
      }
    }
    return hoodFaqs.slice(0, 4);
  }

  const pools = faqPools[family];
  const qCount = pools.questions.length;
  const aCount = pools.answers.length;
  const usedQ = new Set<number>();
  const faqs: ServiceLocationFaq[] = [];

  for (let i = 0; i < 4; i++) {
    let qIdx = variantIndex(`${ctx.seed}:faq-q:${i}`, qCount);
    let aIdx = variantIndex(`${ctx.seed}:faq-a:${i}`, aCount);
    let guard = 0;
    while (usedQ.has(qIdx) && guard < qCount) {
      qIdx = (qIdx + 3) % qCount;
      guard++;
    }
    usedQ.add(qIdx);
    const answer = fill(pools.answers[aIdx], ctx, serviceLabel);
    const localNote = pickVariant(ctx.seed, `faq-local-${i}`, [
      "",
      ` (في سياق {hood}: {landmarks})`,
      ` — ينطبق ذلك على {hood} في {city} حيث {landmarks}`,
      `؛ من تجربتنا في {hood} ({drive} دقيقة وصول تقريبية) ننصح أيضاً بالتهوية الجيدة.`,
    ]);
    faqs.push({
      question: fill(pools.questions[qIdx], ctx, serviceLabel),
      answer: `${answer}${fill(localNote, ctx, serviceLabel)}`,
    });
  }

  return faqs;
}

