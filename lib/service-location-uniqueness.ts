function buildNeighborhoodNarrativeBlocks(ctx: UniquenessCtx, serviceLabel: string): string[] {
  const templates = [
    "{landmarks} وهذا ينعكس مباشرة على طريقة تنفيذ {service} في حي {hood}.",
    "عند التخطيط لـ{service} في {hood}، {city}، نرجع إلى الوصف المحلي: {landmarks}",
    "سؤال شائع من سكان {hood}: كيف يختلف {service} هنا؟ الجواب يبدأ من — {landmarks}",
    "زمن الوصول لحي {hood} نحو {drive} دقيقة من نقطة الفريق؛ في المقابل {landmarks}",
    "قبل أول زيارة {service} في {hood}، ننصح بفهم سياق الحي: {landmarks}",
    "من زيارات متكررة لـ{hood} في {city}، {landmarks}",
    "فريق {service} يجهّز معدات مختلفة حسب {hood} — {landmarks}",
    "عند الحجز من {hood}، اذكر أي تفاصيل إضافية تكمّل: {landmarks}",
  ];
  const indices = [0, 1, 2, 3, 4, 5, 6, 7].map((i) => variantIndex(`${ctx.seed}:narr:${i}`, templates.length));
  const used = new Set<number>();
  const blocks: string[] = [];
  for (let i = 0; i < 6; i++) {
    let idx = indices[i];
    let guard = 0;
    while (used.has(idx) && guard < templates.length) {
      idx = (idx + 1) % templates.length;
      guard++;
    }
    used.add(idx);
    blocks.push(fill(templates[idx], ctx, serviceLabel));
  }
  return blocks;
}

function landmarkFragments(ctx: UniquenessCtx): string[] {
  const parts = ctx.landmarks
    .split(/[؛;،]/)
    .map((s) => s.trim())
    .filter((s) => s.length > 12);
  return parts.length > 0 ? parts : [ctx.landmarks];
}

function frag(ctx: UniquenessCtx, index: number): string {
  const parts = landmarkFragments(ctx);
  return parts[index % parts.length];
}

