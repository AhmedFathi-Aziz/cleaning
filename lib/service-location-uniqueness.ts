export function buildUniquenessCtx(
  city: CityLocation,
  neighborhood: Neighborhood,
  serviceSlug: string,
): UniquenessCtx {
  const seed = `${serviceSlug}/${city.slug}/${neighborhood.slug}`;
  const extraLandmarkNotes = [
    "كثافة السكان والحركة اليومية في هذا الحي تؤثر على توقيت الزيارات ونوع المعدات.",
    "تنوع أعمار المباني بين قديم ومجدّد يفرض مرونة في خطة التنفيذ.",
    "قرب الحي من محاور رئيسية أو أسواق يزيد الطلب قبل نهاية الأسبوع.",
    "وجود فلل بفناء أمامي أو شقق بمداخل مشتركة يغيّر ترتيب العمل.",
    "الارتفاع عن مستوى الشارع والمواقف المحدودة من عوامل نناقشها عند الحجز.",
    "مواسم الغبار المحلية تتطلب جدولة تنظيف خارجية أو تهوية بعد الأعمال الرطبة.",
    "قرب المدارس أو المراكز التجارية يحدد أوقاتاً أفضل لتجنب الازدحام.",
    "بعض القطع في الحي أهدأ من غيرها — نستفيد من ذلك في المواعيد الصباحية.",
  ];
  const expandedLandmarks = `${neighborhood.nearbyLandmarksAr} ${fill(
    pickVariant(seed, "landmark-extra", extraLandmarkNotes),
    {
      seed,
      city,
      neighborhood,
      hood: neighborhood.name,
      cityName: city.name,
      citySlug: city.slug,
      landmarks: neighborhood.nearbyLandmarksAr,
      driveMin: neighborhood.approxDriveMinutesFromTeamStaging,
    },
    "",
  )}`;

  return {
    seed,
    city,
    neighborhood,
    hood: neighborhood.name,
    cityName: city.name,
    citySlug: city.slug,
    landmarks: expandedLandmarks,
    driveMin: neighborhood.approxDriveMinutesFromTeamStaging,
  };
}

export type ServiceFamily =
  | "home-cleaning"
  | "deep-cleaning"
  | "fabric"
  | "facade"
  | "tank"
  | "pest"
  | "garden"
  | "construction"
  | "generic";

export function getServiceFamily(serviceSlug: string): ServiceFamily {
  if (
    [
      "house-cleaning",
      "cleaning-company-riyadh",
      "apartment-cleaning-riyadh",
      "villa-cleaning-riyadh",
      "majlis-cleaning-riyadh",
    ].includes(serviceSlug)
  ) {
    return "home-cleaning";
  }
  if (serviceSlug === "deep-home-cleaning") return "deep-cleaning";
  if (serviceSlug === "post-construction-cleaning-riyadh") return "construction";
  if (
    ["carpet-cleaning", "carpet-cleaning-riyadh", "sofa-cleaning", "sofa-cleaning-riyadh"].includes(serviceSlug)
  ) {
    return "fabric";
  }
  if (serviceSlug === "facade-cleaning") return "facade";
  if (serviceSlug === "water-tank-cleaning") return "tank";
  if (
    ["pest-control", "pest-control-riyadh", "cockroach-control-riyadh", "termite-control-riyadh"].includes(serviceSlug)
  ) {
    return "pest";
  }
  if (serviceSlug === "garden-cleaning") return "garden";
  return "generic";
}

function fill(template: string, ctx: UniquenessCtx, serviceLabel: string): string {
  return template
    .replaceAll("{hood}", ctx.hood)
    .replaceAll("{city}", ctx.cityName)
    .replaceAll("{landmarks}", ctx.landmarks)
    .replaceAll("{drive}", String(ctx.driveMin))
    .replaceAll("{service}", serviceLabel);
}

