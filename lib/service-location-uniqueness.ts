/** صفحة برمجية كاملة — كل أقسامها مشتقة من بذرة حي+خدمة فريدة */
export function buildProgrammaticServiceLocationContent(
  city: CityLocation,
  neighborhood: Neighborhood,
  serviceSlug: string,
  serviceLabel: string,
): ProgrammaticLocationContent {
  const ctx = buildUniquenessCtx(city, neighborhood, serviceSlug);
  const family = getServiceFamily(serviceSlug);
  const specific = getNeighborhoodSpecificContent(ctx.citySlug, ctx.neighborhood.slug);

  const customerProblems = buildCustomerProblems(ctx, family, serviceLabel);
  const serviceRecommendations = buildServiceRecommendations(ctx, family, serviceLabel);
  const uniqueIntro = buildUniqueLocalIntro(ctx, serviceLabel, family);
  const uniqueFaqs = buildUniqueFaqs(ctx, family, serviceLabel);
  const preparationBullets = buildPreparationBullets(ctx, serviceLabel);
  const narratives = buildNeighborhoodNarrativeBlocks(ctx, serviceLabel);

  const problemsSection: ServiceSection = {
    heading: `تحديات ${serviceLabel} لسكان حي ${ctx.hood} (${ctx.cityName})`,
    paragraphs: specific
      ? [`من واقع طلبات ${serviceLabel} في حي ${ctx.hood} — مشاكل نراها غالباً في هذا الحي تحديداً:`]
      : [`${ctx.landmarks} — من واقع طلبات ${serviceLabel} في هذا الحي:`],
    bullets: customerProblems,
  };

  const recommendationsSection: ServiceSection = {
    heading: `توصيات ${serviceLabel} — حي ${ctx.hood}، ${ctx.driveMin} دقيقة وصول تقريبية`,
    paragraphs: specific
      ? [`بناءً على الحالة المحلية في ${ctx.hood}، هذه توصيات عملية قبل الحجز:`]
      : [`${frag(ctx, 2)} — نصائح عملية قبل الحجز من حي ${ctx.hood}:`],
    bullets: serviceRecommendations,
  };

  const contextSection: ServiceSection = specific
    ? {
        heading: `${serviceLabel} في حي ${ctx.hood} — سياق محلي (${ctx.cityName})`,
        paragraphs: [ctx.landmarks, cityClimateNote(ctx.citySlug)],
      }
    : {
        heading: `${serviceLabel} في حي ${ctx.hood} — سياق محلي (${ctx.cityName})`,
        paragraphs: [
          buildLandmarkContextParagraph(ctx, serviceLabel),
          fill(
            pickVariant(ctx.seed, "ctx-drive", [
              "عند طلب {service} في حي {hood}، {city}، نأخذ نوع العمارة وكثافة الحركة وطريقة الوصول في الحسبان — {landmarks}",
              "تقدير الوصول لحي {hood} يبدأ من {drive} دقيقة — يختلف حسب الزحمة؛ {landmarks}",
              "نمط الشوارع في {hood} يؤثر على حجم المعدات لـ{service}: {landmarks}",
            ]),
            ctx,
            serviceLabel,
          ),
        ],
      };

  const narrativeSection: ServiceSection = {
    heading: `سياق حي ${ctx.hood} و${serviceLabel}`,
    paragraphs: narratives,
  };

  const localCaseSection: ServiceSection | null = specific
    ? {
        heading: `حالة محلية من حي ${ctx.hood}`,
        paragraphs: [specific.localCase],
        bullets: specific.localExamples,
      }
    : null;

  const sections: ServiceSection[] = [
    contextSection,
    ...(localCaseSection ? [localCaseSection] : []),
    ...(specific ? [] : [narrativeSection]),
    problemsSection,
    recommendationsSection,
    buildSchedulingSection(ctx, serviceLabel),
    buildExecutionSection(ctx, family, serviceLabel),
  ];

  const highlight = getNeighborhoodServiceHighlights(city, neighborhood).find((b) => b.slug === serviceSlug);
  if (highlight) {
    sections.push({
      heading: highlight.heading,
      paragraphs: [frag(ctx, 4), ...highlight.paragraphs],
      bullets: highlight.bullets,
    });
  }

  sections.push(buildCrossServiceSection(ctx));

  return {
    localIntro: uniqueIntro,
    customerProblems,
    serviceRecommendations,
    sections,
    faqs: uniqueFaqs,
    preparationBullets,
  };
}
